// As root, the driver shows up in an environment, read-only and with its
// links.
func TestProvideNVIDIA(t *testing.T) {
	if os.Geteuid() != 0 {
		t.Skip("needs root to mount")
	}
	dev, libraries := fakeDriver(t)
	d, err := findNVIDIA(dev, libraries, func(string) (string, error) { return "", errors.New("none") })
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	d.Cache = filepath.Join(t.TempDir(), "cuda")
	t.Cleanup(func() {
		tool.Run("umount", "-R", filepath.Join(root, nvidiaDir))
		for _, device := range d.Devices {
			tool.Run("umount", filepath.Join(root, device))
		}
	})
	if err := provideNVIDIA(root, d); err != nil {
		t.Fatal(err)
	}
	lib := filepath.Join(root, nvidiaDir, "lib64")
	if data, err := os.ReadFile(filepath.Join(lib, "libcuda.so.1")); err != nil || string(data) != "libcuda.so" {
		t.Errorf("libcuda.so.1 reads %q, %v", data, err)
	}
	if err := os.WriteFile(filepath.Join(lib, "libcuda.so.580.95.05"), []byte("x"), 0o755); err == nil {
		t.Error("the host's libcuda is writable from the environment")
	}
	if _, err := os.Stat(filepath.Join(root, dev, "nvidia1")); err != nil {
		t.Errorf("device: %v", err)
	}
	// CUDA's cache outlives the session: it is the host's directory.
	if err := os.WriteFile(filepath.Join(root, nvidiaDir, "cache", "kernel"), []byte("k"), 0o644); err != nil {
		t.Fatal(err)
	}
	if data, err := os.ReadFile(filepath.Join(d.Cache, "kernel")); err != nil || string(data) != "k" {
		t.Errorf("the kept cache has %q, %v", data, err)
	}
}
